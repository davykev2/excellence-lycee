function lessonSlug(title: string) {
  return title
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("fr")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 64);
}

export const curriculumLessonTitles: CurriculumLessonTitle[] = Object.entries(curriculumByLevel).flatMap(
  ([levelId, curriculum]) =>
    (Object.entries(curriculum) as Array<[SubjectId, readonly LessonSeed[]]>).flatMap(([subjectId, lessons]) =>
      lessons.map((seed, index) => {
        const details = typeof seed === "string" ? { title: seed } : seed;
        return {
          ...details,
          id: `${levelId}-${subjectId}-${String(index + 1).padStart(2, "0")}-${lessonSlug(details.title)}`,
          levelId,
          subjectId,
          sequence: index + 1,
        };
      }),
    ),
);

export function getCurriculumLessonTitles(levelId: string, subjectId: SubjectId) {
  return curriculumLessonTitles.filter((lesson) => lesson.levelId === levelId && lesson.subjectId === subjectId);
}
