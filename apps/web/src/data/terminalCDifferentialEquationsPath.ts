const sourceDocument = "TC Maths leçon 18 Equations différentielles.pdf";

const choice = (
  prompt: string,
  options: string[],
  correctIndex: number,
  explanation: string,
  sourceLabel: string,
  points = 1,
): LessonQuestion => ({ type: "choice", prompt, options, correctIndex, explanation, sourceLabel, points });

const short = (
  prompt: string,
  acceptedAnswers: string[],
  explanation: string,
  sourceLabel: string,
  points = 1,
): LessonQuestion => ({
  type: "short-answer",
  prompt,
  options: [],
  correctIndex: 0,
  acceptedAnswers,
  explanation,
  sourceLabel,
  points,
});

const truth = (
  prompt: string,
  isTrue: boolean,
  explanation: string,
  sourceLabel: string,
  points = 1,
) => choice(prompt, ["Vrai", "Faux"], isTrue ? 0 : 1, explanation, sourceLabel, points);

const md = (lines: string[]) => lines.join("\n");

interface OfficialLevelSeed {
  id: string;
  title: string;
  summary: string;
  pages: string;
  section: string;
  durationMinutes: number;
  kind?: LessonKind;
  body: string;
  keyPoint: string;
  example: string;
  methodSteps: string[];
  timeline: [TimelineInteractionItem, TimelineInteractionItem, ...TimelineInteractionItem[]];
  interaction?: LessonInteraction;
  questions: LessonQuestion[];
  corrections?: string[];
  tip?: string;
}

function progressionWeight(index: number) {
  return 50 + Math.min(index, 7) * 5;
}

function officialLevel(index: number, seed: OfficialLevelSeed): LearningLesson {
  return {
    id: seed.id,
    title: seed.title,
    summary: seed.summary,
    durationMinutes: seed.durationMinutes,
    xp: progressionWeight(index),
    kind: seed.kind ?? "concept",
    source: {
      documentTitle: sourceDocument,
      pages: seed.pages,
      section: seed.section,
      fidelity: seed.corrections?.length ? "faithful-corrected" : "faithful",
      corrections: seed.corrections ?? [],
    },
    concept: {
      eyebrow: "Niveau " + (index + 1) + " • Cours officiel",
      title: seed.title,
      explanation: seed.summary,
      bodyMarkdown: seed.body,
      notation: seed.keyPoint,
      notationTex: seed.keyPoint,
      example: "$$" + seed.example + "$$",
    },
    interaction: seed.interaction ?? {
      kind: "timeline",
      eyebrow: "Repères",
      title: "Reconstruis la démarche",
      instruction: "Parcours les étapes dans l’ordre avant de lancer les exercices.",
      observation: "Chaque repère relie la forme de l’équation, la famille de solutions et le contrôle par dérivation.",
      items: seed.timeline,
    },
    method: {
      eyebrow: "Méthode",
      title: "Réussir : " + seed.title.toLocaleLowerCase("fr"),
      introduction:
        "Identifie d’abord la famille de l’équation, écris sa solution générale, puis utilise les conditions données.",
      steps: seed.methodSteps,
      example: {
        prompt: "Exemple guidé du document",
        work: "$$" + seed.example + "$$",
        result: "$$" + seed.keyPoint + "$$",
      },
      tip:
        seed.tip ??
        "Astuce mémoire de Davy : forme, famille, constantes, conditions, vérification — toujours dans cet ordre.",
    },
    question: seed.questions[0],
    questions: seed.questions,
  };
}

